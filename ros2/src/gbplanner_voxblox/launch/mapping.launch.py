from pathlib import Path
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription
from launch.conditions import IfCondition
from launch.substitutions import LaunchConfiguration
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue
from ament_index_python.packages import get_package_share_directory


def generate_launch_description():
    local = Path(get_package_share_directory('gbplanner_local'))
    tsdf = Path(get_package_share_directory('gbplanner_voxblox'))
    flag = lambda name: ParameterValue(LaunchConfiguration(name), value_type=bool)
    return LaunchDescription([
        DeclareLaunchArgument('storage', default_value='dense', choices=['dense','sparse'],
            description='Dense bounded projection or all observed Voxblox voxels'),
        DeclareLaunchArgument('distance_field', default_value='tsdf', choices=['tsdf','esdf']),
        DeclareLaunchArgument('use_tf_transforms', default_value='true'),
        DeclareLaunchArgument('timestamp_tolerance_sec', default_value='0.001'),
        DeclareLaunchArgument('enable_icp', default_value='false'),
        DeclareLaunchArgument('accumulate_icp_corrections', default_value='true'),
        DeclareLaunchArgument('max_block_distance_from_body', default_value='3.4028234663852886e+38',
            description='Keep blocks whose origins are within this distance of the raw sensor pose'),
        DeclareLaunchArgument('esdf', default_value='false'),
        DeclareLaunchArgument('esdf_max_distance_m', default_value='2.0'),
        DeclareLaunchArgument('clear_sphere_for_planning', default_value='false'),
        DeclareLaunchArgument('clear_sphere_pose_source', default_value='sensor', choices=['sensor','odometry']),
        DeclareLaunchArgument('clear_sphere_radius', default_value='1.5'),
        DeclareLaunchArgument('occupied_sphere_radius', default_value='5.0'),
        DeclareLaunchArgument('publish_tsdf_map', default_value='false'),
        DeclareLaunchArgument('publish_esdf_map', default_value='false'),
        DeclareLaunchArgument('publish_map_every_n_sec', default_value='1.0'),
        DeclareLaunchArgument('publish_pointclouds_on_update', default_value='false',
            description='Publish full visualization products with each planning-map snapshot'),
        DeclareLaunchArgument('publish_pointclouds', default_value='false',
            description='Publish full visualization after dirty mesh timer updates when on-update publishing is disabled'),
        DeclareLaunchArgument('publish_slices', default_value='false'),
        DeclareLaunchArgument('slice_level', default_value='0.5'),
        DeclareLaunchArgument('publish_traversable', default_value='false'),
        DeclareLaunchArgument('traversability_radius', default_value='1.0'),
        DeclareLaunchArgument('occupancy_min_distance_voxel_size_factor', default_value='1.0'),
        DeclareLaunchArgument('load_map_file', default_value=''),
        DeclareLaunchArgument('map_file', default_value=''),
        DeclareLaunchArgument('mesh_file', default_value=''),
        DeclareLaunchArgument('color_mode', default_value='colors',
            choices=['none','colors','color','height','normals','gray','lambert','lambert_color']),
        DeclareLaunchArgument('update_mesh_every_n_sec', default_value='0.5',
            description='Surface mesh update interval; zero disables periodic generation'),
        DeclareLaunchArgument('seed', default_value='42'),
        DeclareLaunchArgument('sensor_config', default_value=str(local/'config/local.yaml'),
            description='ROS parameter file for planner sensors, mapper inputs, T_B_D/T_B_C extrinsics and ICP settings'),
        DeclareLaunchArgument('global_planning', default_value='false'),
        DeclareLaunchArgument('background', default_value='false'),
        DeclareLaunchArgument('geofence', default_value='false'),
        DeclareLaunchArgument('mission', default_value='false'),
        DeclareLaunchArgument('mission_homing_speed', default_value='0.9'),
        DeclareLaunchArgument('control', default_value='false'),
        DeclareLaunchArgument('planner_trigger_lead_time', default_value='0.0'),
        DeclareLaunchArgument('rviz', default_value='false'),
        DeclareLaunchArgument('visualization', default_value='false'),
        Node(package='gbplanner_local', executable='local_planner_node', name='gbplanner_local',
             parameters=[str(local/'config/local.yaml'), LaunchConfiguration('sensor_config'), {
                 'map.storage': LaunchConfiguration('storage'),
                 'sampling.seed': ParameterValue(LaunchConfiguration('seed'), value_type=int),
                 'planning.geofence_checking_enable': flag('geofence'), 'global.enable': flag('global_planning'), 'global.background_enable': flag('background'),
                 'mission.enabled': flag('mission'),
                 'mission.homing_speed': ParameterValue(LaunchConfiguration('mission_homing_speed'), value_type=float)}], output='screen'),
        Node(package='gbplanner_voxblox', executable='voxblox_mapper_node', name='voxblox_mapper',
             parameters=[str(tsdf/'config/test_room.yaml'), LaunchConfiguration('sensor_config'), {
                 'map.storage': LaunchConfiguration('storage'),
                 'map.distance_field': LaunchConfiguration('distance_field'), 'esdf.enabled': flag('esdf'),
                 'use_tf_transforms': flag('use_tf_transforms'),
                 'timestamp_tolerance_sec': ParameterValue(LaunchConfiguration('timestamp_tolerance_sec'),value_type=float),
                 'enable_icp': flag('enable_icp'),
                 'accumulate_icp_corrections': flag('accumulate_icp_corrections'),
                 'max_block_distance_from_body': ParameterValue(LaunchConfiguration('max_block_distance_from_body'),value_type=float),
                 'esdf.max_distance': ParameterValue(LaunchConfiguration('esdf_max_distance_m'),value_type=float),
                 'esdf.clear_sphere_for_planning': flag('clear_sphere_for_planning'),
                 'esdf.clear_sphere_pose_source': LaunchConfiguration('clear_sphere_pose_source'),
                 'esdf.clear_sphere_radius': ParameterValue(LaunchConfiguration('clear_sphere_radius'),value_type=float),
                 'esdf.occupied_sphere_radius': ParameterValue(LaunchConfiguration('occupied_sphere_radius'),value_type=float),
                 'publish_tsdf_map': flag('publish_tsdf_map'),
                 'publish_esdf_map': flag('publish_esdf_map'),
                 'publish_map_every_n_sec': ParameterValue(LaunchConfiguration('publish_map_every_n_sec'),value_type=float),
                 'publish_pointclouds_on_update': flag('publish_pointclouds_on_update'),
                 'publish_pointclouds': flag('publish_pointclouds'),
                 'publish_slices': flag('publish_slices'),
                 'slice_level': ParameterValue(LaunchConfiguration('slice_level'),value_type=float),
                 'publish_traversable': flag('publish_traversable'),
                 'traversability_radius': ParameterValue(LaunchConfiguration('traversability_radius'),value_type=float),
                 'occupancy_min_distance_voxel_size_factor': ParameterValue(LaunchConfiguration('occupancy_min_distance_voxel_size_factor'),value_type=float),
                 'load_map_file': ParameterValue(LaunchConfiguration('load_map_file'),value_type=str),
                 'map_file': ParameterValue(LaunchConfiguration('map_file'),value_type=str),
                 'color_mode': LaunchConfiguration('color_mode'),
                 'update_mesh_every_n_sec': ParameterValue(LaunchConfiguration('update_mesh_every_n_sec'),value_type=float),
                 'mesh_file': ParameterValue(LaunchConfiguration('mesh_file'),value_type=str)}], output='screen'),
        Node(package='gbplanner_local', executable='control_node.py', name='gbplanner_control',
             condition=IfCondition(LaunchConfiguration('control')),
             parameters=[{'require_mission_status': flag('mission'),
                 'planner_trigger_lead_time': ParameterValue(LaunchConfiguration('planner_trigger_lead_time'), value_type=float)}], output='screen'),
        Node(package='rviz2', executable='rviz2', arguments=['-d', str(tsdf/'config/voxblox.rviz')],
             condition=IfCondition(LaunchConfiguration('rviz')), output='screen'),
        IncludeLaunchDescription(PythonLaunchDescriptionSource(str(local/'launch/visualization.launch.py')),
             condition=IfCondition(LaunchConfiguration('visualization'))),
    ])
