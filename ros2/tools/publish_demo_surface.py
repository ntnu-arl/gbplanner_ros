#!/usr/bin/env python3
"""Periodically request the mapper's existing pointcloud products for a demo.

Every product is generated by the real mapper's /publish_pointclouds Trigger
service. This client does not create clouds or change maps, parameters or robot
control. Its additional mapper workload is solely for visualization.

Only one request may be outstanding. A slow request remains pending even after
the diagnostic timeout; the next interval starts after its eventual response.
"""
import argparse
import json
import math
import signal
import time

import rclpy
from rclpy.clock import Clock, ClockType
from rclpy.executors import ExternalShutdownException
from rclpy.node import Node
from std_srvs.srv import Trigger


class DemoSurfacePublisher(Node):
    def __init__(self, interval, request_timeout):
        super().__init__('publish_demo_surface')
        self.interval = interval
        self.request_timeout = request_timeout
        self.client = self.create_client(Trigger, '/publish_pointclouds')
        self.started = time.monotonic()
        self.next_request = self.started
        self.future = None
        self.request_started = None
        self.timeout_reported = False
        self.stats = {'requests': 0, 'successes': 0, 'failures': 0, 'timeouts': 0}
        # Display scheduling uses wall elapsed time even if simulation pauses.
        self.steady_clock = Clock(clock_type=ClockType.STEADY_TIME)
        self.timer = self.create_timer(.25, self.tick, clock=self.steady_clock)
        self.report('waiting_for_service', interval_s=interval,
                    request_timeout_s=request_timeout)

    def report(self, event, **details):
        print(json.dumps(dict(event=event, service='/publish_pointclouds',
                              elapsed_s=time.monotonic() - self.started,
                              in_flight=self.future is not None,
                              **self.stats, **details), allow_nan=False), flush=True)

    def tick(self):
        now = time.monotonic()
        if self.future is not None:
            if not self.future.done():
                if not self.timeout_reported and now - self.request_started >= self.request_timeout:
                    self.timeout_reported = True
                    self.stats['timeouts'] += 1
                    self.report('request_slow_still_waiting',
                                request_elapsed_s=now - self.request_started)
                # Do not cancel or replace a slow future: cancellation on the
                # client would not stop the mapper's current product work.
                return
            future = self.future
            elapsed = now - self.request_started
            self.future = None
            self.next_request = now + self.interval
            try:
                response = future.result()
                if response is None:
                    raise RuntimeError('Service returned no response')
                self.stats['successes' if response.success else 'failures'] += 1
                self.report('response', success=bool(response.success),
                            message=response.message, request_elapsed_s=elapsed,
                            previously_timed_out=self.timeout_reported)
            except Exception as error:
                self.stats['failures'] += 1
                self.report('request_failed', error=str(error), request_elapsed_s=elapsed)
            return
        if now < self.next_request or not self.client.service_is_ready():
            return
        try:
            self.future = self.client.call_async(Trigger.Request())
        except Exception as error:
            self.stats['failures'] += 1
            self.next_request = now + self.interval
            self.report('request_not_sent', error=str(error))
            return
        self.stats['requests'] += 1
        self.request_started = now
        self.timeout_reported = False
        self.report('request_sent')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--interval', type=float, default=10.,
                        help='Seconds after a completed request before another (default: 10)')
    parser.add_argument('--request-timeout', type=float, default=30.,
                        help='Report a slow request once, without replacing it (default: 30)')
    args, ros_args = parser.parse_known_args()
    if not math.isfinite(args.interval) or args.interval < 10.:
        parser.error('--interval must be finite and at least 10 seconds')
    if not math.isfinite(args.request_timeout) or args.request_timeout <= 0.:
        parser.error('--request-timeout must be finite and positive')
    rclpy.init(args=ros_args)
    node = DemoSurfacePublisher(args.interval, args.request_timeout)
    try:
        rclpy.spin(node)
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        signal.signal(signal.SIGINT, signal.SIG_IGN)
        node.timer.cancel()
        node.report('stopped', pending_request_elapsed_s=(
            time.monotonic() - node.request_started if node.future is not None else None))
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
