#!/usr/bin/env python3
"""Check retained automatic global targets through native ROS services.

Uses synthetic occupancy/odometry and a graph previously generated by the real
planner in check_frontier_switch.py. No fabricated graph or planner reply and
no action execution or robot dynamics. The PCI PlanAhead handoff is separately
checked against its source; it is not represented as an end-to-end action run.
"""
import argparse
import ast
import copy
import hashlib
import json
import math
import os
from pathlib import Path
import signal
import struct
import subprocess
import time
import traceback
from types import SimpleNamespace


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def xyz(pose):
    return [pose.position.x, pose.position.y, pose.position.z]


def route(poses):
    return [xyz(pose)+[pose.orientation.x, pose.orientation.y,
                      pose.orientation.z, pose.orientation.w] for pose in poses]


def check_pci_source(path):
    """Check the actual flag expression and source chain without mock services."""
    source = path.read_text()
    module = ast.parse(source)
    control = next(node for node in module.body if isinstance(node, ast.ClassDef)
                   and node.name == 'PlannerControl')
    methods = {node.name: node for node in control.body if isinstance(node, ast.FunctionDef)}
    assignments = [node for node in ast.walk(methods['request_plan']) if isinstance(node, ast.Assign)]
    saved = next(node for node in assignments if any(isinstance(target, ast.Name)
                 and target.id == 'automatic_repositioning' for target in node.targets))
    cleared = next(node for node in assignments if any(ast.unparse(target) == 'self.ahead_global_required'
                   for target in node.targets) and isinstance(node.value, ast.Constant) and node.value.value is False)
    sent = next(node for node in assignments if any(ast.unparse(target) == 'request.automatic_repositioning'
                for target in node.targets))
    require(saved.lineno < cleared.lineno < sent.lineno and
            isinstance(sent.value, ast.Name) and sent.value.id == 'automatic_repositioning',
            'PCI must preserve its latch before clearing and forwarding it')
    expression = compile(ast.Expression(saved.value), str(path), 'eval')
    cases = []
    for mode, latch, explicit, expected in (
            ('global', True, None, True), ('global', False, None, False),
            ('global', False, {'id': 9}, False), ('global', True, {'id': 9}, False),
            ('local', True, None, False), ('homing', True, None, False)):
        actual = eval(expression, {'__builtins__': {}},
                      {'mode': mode, 'self': SimpleNamespace(ahead_global_required=latch, explicit_global=explicit)})
        require(actual is expected, 'PCI automatic_repositioning flag expression changed')
        cases.append({'mode': mode, 'ahead_global_required': latch,
                      'explicit_global': explicit is not None, 'automatic_repositioning': actual})
    ahead_latch = any(isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant)
                      and node.value.value is True and any(ast.unparse(target) == 'self.ahead_global_required'
                      for target in node.targets) for node in ast.walk(methods['ahead_planned']))
    handoff = any(isinstance(node, ast.If) and ast.unparse(node.test) == 'self.ahead_global_required'
                  and any(isinstance(call, ast.Call) and ast.unparse(call.func) == 'self.request_plan'
                          and call.args and isinstance(call.args[0], ast.Constant)
                          and call.args[0].value == 'global'
                          for branch in node.body for call in ast.walk(branch))
                  for node in ast.walk(methods['tick']))
    require(ahead_latch and handoff, 'PCI PlanAhead result no longer reaches the global handoff')
    return {'kind': 'static source contract and evaluated flag expression; no action run',
            'source': str(path), 'sha256': hashlib.sha256(source.encode()).hexdigest(),
            'capture_line': saved.lineno, 'consume_line': cleared.lineno, 'forward_line': sent.lineno,
            'ahead_latch_and_tick_handoff': True, 'flag_cases': cases}


def main():
    workspace = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=workspace/'results/global_repositioning/summary.json')
    parser.add_argument('--snapshot', type=Path, default=workspace/'results/frontier_switch/native_frontier.gbmem')
    parser.add_argument('--source-summary', type=Path, default=workspace/'results/frontier_switch/summary.json')
    parser.add_argument('--timeout', type=float, default=120.)
    args = parser.parse_args()
    require(math.isfinite(args.timeout) and args.timeout > 0., 'Timeout must be positive')
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    started, deadline = time.monotonic(), time.monotonic()+args.timeout
    os.environ.setdefault('ROS_DOMAIN_ID', str(100+os.getpid()%80))
    probe, initialized = None, False
    summary = {'status': 'failed', 'scope': __doc__, 'domain': os.environ['ROS_DOMAIN_ID'],
               'launches': [], 'checks': {}, 'observations': {}}
    try:
        snapshot, source_summary = args.snapshot.resolve(), args.source_summary.resolve()
        provenance = json.loads(source_summary.read_text())
        require(provenance['status'] == 'passed' and provenance['seed']['metrics']['frontier_exists'],
                'Source check must document a successful native frontier graph')
        require(Path(provenance['seed']['snapshot']).name == snapshot.name,
                'Snapshot filename differs from its native source record')
        require(snapshot.is_file() and snapshot.stat().st_size > 0, 'Native frontier snapshot is missing')
        summary['snapshot'] = {'path': str(snapshot), 'sha256': hashlib.sha256(snapshot.read_bytes()).hexdigest(),
            'source_summary': str(source_summary), 'source_summary_sha256': hashlib.sha256(source_summary.read_bytes()).hexdigest(),
            'generator': 'check_frontier_switch.py: seed local_planner_node then gbplanner/save_graph',
            'reuse': 'existing native snapshot; graph bytes are read without alteration'}
        summary['checks']['pci_ahead_handoff_source'] = check_pci_source(workspace/'src/gbplanner_local/scripts/control_node.py')

        import rclpy
        from geometry_msgs.msg import Pose
        from nav_msgs.msg import Odometry
        from planner_msgs.srv import PciStop, PlanAhead, PlannerGlobal, PlannerSrv, PlannerStringTrigger
        from rclpy.node import Node
        from rclpy.qos import DurabilityPolicy, QoSProfile, ReliabilityPolicy
        from sensor_msgs.msg import PointCloud2, PointField
        from std_msgs.msg import Bool, String
        from std_srvs.srv import Trigger

        rclpy.init(args=[])
        initialized = True
        durable = QoSProfile(depth=20, reliability=ReliabilityPolicy.RELIABLE,
                             durability=DurabilityPolicy.TRANSIENT_LOCAL)
        origin, dimensions, resolution = (-4., -5., -3.), (36, 20, 12), .5
        parameters = {
            'map.resolution': resolution, 'map.origin': list(origin), 'map.dimensions': list(dimensions),
            'global.enable': True, 'global.auto_home': True, 'global.background_enable': False,
            'sampling.min': [-1., -1., -.2], 'sampling.max': [1., 1., .2], 'sampling.seed': 42,
            'planning.max_vertices': 32, 'planning.max_attempts': 1200,
            'planning.edge_min': .35, 'planning.edge_max': 1., 'planning.neighbor_max': 1.5,
            'planning.path_safety_enhance_enable': False,
            'sensor.range': 2., 'sensor.horizontal_fov': 2.*math.pi, 'sensor.vertical_fov': .3,
            'sensor.horizontal_resolution': .3, 'sensor.vertical_resolution': .15,
            'gain.free': .05, 'gain.unknown': 1., 'gain.frontier_threshold': .05,
        }
        summary['parameters'] = parameters

        def make_map():
            # Identical synthetic occupancy used to produce the native seed.
            cloud = PointCloud2()
            cloud.header.frame_id, cloud.height, cloud.width = 'map', 1, math.prod(dimensions)
            cloud.point_step, cloud.row_step, cloud.is_dense = 16, cloud.width*16, True
            cloud.fields = [PointField(name=name, offset=4*i, datatype=PointField.FLOAT32, count=1)
                            for i, name in enumerate(('x', 'y', 'z'))]
            cloud.fields.append(PointField(name='occupancy', offset=12, datatype=PointField.INT8, count=1))
            data, offset = bytearray(cloud.row_step), 0
            for z in range(dimensions[2]):
                for y in range(dimensions[1]):
                    for x in range(dimensions[0]):
                        point = [origin[i]+(value+.5)*resolution for i, value in enumerate((x, y, z))]
                        struct.pack_into('<fffbxxx', data, offset, *point, -1 if point[0] >= 6. else 0)
                        offset += 16
            cloud.data = bytes(data)
            return cloud

        class Probe(Node):
            def __init__(self):
                self.namespace_name = f'/global_repositioning_{os.getpid()}'
                super().__init__('probe', namespace=self.namespace_name)
                self.processes, self.service_clients, self.metrics, self.globals, self.stops = [], {}, [], [], []
                self.closed, self.position = False, [0., 0., 0.]
                self.maps = self.create_publisher(PointCloud2, 'voxel_map', durable)
                self.odometry = self.create_publisher(Odometry, 'odometry', 10)
                self.stop_topic = 'planner_control_interface/stop_request'
                self.stop_pub = self.create_publisher(Bool, self.stop_topic, 10)
                self.create_subscription(Bool, self.stop_topic, lambda m:self.stops.append(m.data), 10)
                self.create_subscription(String, 'planning_metrics',
                    lambda m:self.metrics.append(self.decode('planning_metrics', m.data)), durable)
                self.create_subscription(String, 'global_metrics',
                    lambda m:self.globals.append(self.decode('global_metrics', m.data)), durable)
                self.create_timer(.05, self.publish_odometry)

            def launch(self, executable, settings):
                command = ['ros2', 'run', 'gbplanner_local', executable, '--ros-args', '-r', '__ns:='+self.namespace_name]
                for key, value in settings.items():
                    command += ['-p', key+':='+json.dumps(value)]
                log = output.parent/(executable+'.log')
                with log.open('w') as stream:
                    process = subprocess.Popen(command, stdout=stream, stderr=subprocess.STDOUT,
                                               start_new_session=True, env=dict(os.environ))
                self.processes.append((process, log))
                summary['launches'].append(command)

            def until(self, predicate, label, seconds=15.):
                limit = min(deadline, time.monotonic()+seconds)
                while not predicate():
                    for process, log in self.processes:
                        if process.poll() is not None:
                            raise RuntimeError(f'{process.returncode}: see {log}')
                    if time.monotonic() >= limit:
                        raise TimeoutError(label)
                    rclpy.spin_once(self, timeout_sec=.02)

            def call(self, name, request, kind=Trigger):
                if name not in self.service_clients:
                    self.service_clients[name] = self.create_client(kind, name)
                client = self.service_clients[name]
                self.until(client.service_is_ready, name+' discovery')
                future = client.call_async(request)
                self.until(future.done, name+' response')
                response = future.result()
                require(response is not None, name+': empty response')
                return response

            def decode(self, name, raw):
                try:
                    return json.loads(raw)
                except json.JSONDecodeError:
                    path = output.parent/(name+'_invalid.txt')
                    path.write_text(raw)
                    summary['invalid_json'] = str(path)
                    raise

            def status(self, name='global_status'):
                return self.decode(name, self.call(name, Trigger.Request()).message)

            def publish_odometry(self):
                message = Odometry()
                message.header.frame_id, message.child_frame_id = 'map', 'base_link'
                message.header.stamp = self.get_clock().now().to_msg()
                message.pose.pose.position.x, message.pose.pose.position.y, message.pose.pose.position.z = self.position
                message.pose.pose.orientation.w = 1.
                self.odometry.publish(message)

            def move(self, point):
                self.position = list(point)
                self.publish_odometry()
                self.until(lambda:math.dist(self.status('sensor_gain').get('root', [1.e6]*4)[:3], self.position)<1.e-8,
                           'native synthetic odometry acknowledgment')

            def initialize(self):
                self.until(lambda:self.maps.get_subscription_count()>0 and self.odometry.get_subscription_count()>=2,
                           'planner and PCI subscriptions')
                before = self.status('map_status')['map_revision']
                cloud = make_map()
                cloud.header.stamp = self.get_clock().now().to_msg()
                self.maps.publish(cloud)
                self.until(lambda:self.status('map_status')['map_revision']==before+1, 'map accepted')
                self.move([0., 0., 0.])
                self.until(lambda:self.status()['vertices']>0, 'native home established')
                self.storage()

            def storage(self):
                request = PlannerStringTrigger.Request()
                request.message = str(snapshot)
                require(self.call('gbplanner/load_graph', request, PlannerStringTrigger).success,
                        'Native graph load failed')

            def plan(self, hypothetical=None):
                request = PlannerSrv.Request()
                request.header.frame_id, request.bound_mode = 'map', 3
                request.root_pose.orientation.w = 0.
                if hypothetical is not None:
                    request.root_pose = copy.deepcopy(hypothetical)
                before = len(self.metrics)
                response = self.call('planner', request, PlannerSrv)
                self.until(lambda:len(self.metrics)>before, 'local metrics')
                return response, self.metrics[-1]

            def global_plan(self, automatic=False):
                request = PlannerGlobal.Request()
                request.ignore_time, request.bound_mode = True, 3
                request.automatic_repositioning = automatic
                before = len(self.globals)
                response = self.call('planner_global', request, PlannerGlobal)
                self.until(lambda:len(self.globals)>before, 'global metrics')
                metric = self.globals[-1]
                require(metric['success'] and len(response.path)>1 and not response.homing,
                        'Native global frontier route failed: '+str(metric))
                return response, metric

            def close(self):
                if self.closed:
                    return
                self.closed = True
                for process, _ in reversed(self.processes):
                    if process.poll() is not None:
                        continue
                    try:
                        os.killpg(process.pid, signal.SIGINT)
                    except ProcessLookupError:
                        pass
                    try:
                        process.wait(timeout=3.)
                    except subprocess.TimeoutExpired:
                        try:
                            os.killpg(process.pid, signal.SIGKILL)
                        except ProcessLookupError:
                            pass
                        process.wait(timeout=1.)
                self.destroy_node()

        probe = Probe()
        probe.launch('local_planner_node', parameters)
        probe.launch('control_node.py', {'planner_trigger_lead_time': 0.})
        probe.initialize()
        initial = probe.status()
        require(initial['frontiers']>0 and not initial['repositioning_active'], 'Fixture did not load inactive native frontiers')
        manual, manual_metric = probe.global_plan()
        require(not probe.status()['repositioning_active'], 'Manual global request activated automatic target retention')
        summary['observations']['manual_global'] = {'metrics': manual_metric, 'path': route(manual.path)}

        rounds = []
        for index, expected in enumerate((1, 2, 3, 0), start=1):
            response, metric = probe.plan()
            status = probe.status()
            require(metric['gain_evaluated'] and not metric['frontier_exists'] and metric['gain']>0.,
                    'Local round must evaluate positive gain without frontiers')
            require(status['low_gain_iterations']==expected and metric['auto_global']['counted'],
                    'Native no-frontier counter did not advance')
            require(metric['auto_global']['triggered']==(index==4), 'Native switch did not occur exactly on fourth round')
            require(status['repositioning_active']==(index==4), 'Target retention activated on wrong round')
            require(response.status==(response.K_REPOSITIONING if index==4 else response.K_FORWARD),
                    'Native round returned wrong planning status')
            rounds.append({'round': index, 'metrics': metric, 'global_status': status, 'path': route(response.path)})
        require(response.path, 'Fourth native round returned no retained global route')
        target, target_pose = status['repositioning_target'], copy.deepcopy(response.path[-1])
        target_xyz = xyz(target_pose)
        target_distance = math.dist(probe.position, target_xyz)
        require(target>0 and target_distance>5., 'Native selected frontier is not beyond the 5 m retention boundary')
        summary['observations']['four_round_activation'] = rounds
        summary['observations']['retained_target'] = {'id': target, 'xyz': target_xyz, 'initial_distance_m': target_distance}

        repeated = []
        for _ in range(2):
            resumed, metric = probe.plan()
            state = probe.status()
            require(resumed.status==resumed.K_REPOSITIONING and resumed.path and xyz(resumed.path[-1])==target_xyz,
                    'Repeated actual-root request changed the retained target')
            require(not metric['gain_evaluated'] and metric['gain_evaluations']==0,
                    'Retained global request reran local gain evaluation')
            require(state['repositioning_active'] and state['repositioning_target']==target and
                    metric['auto_global']['retained_active'] and metric['auto_global']['retained_target']==target,
                    'Retained target state or metrics changed')
            repeated.append({'metrics': metric, 'path': route(resumed.path)})
        summary['observations']['repeated_actual_roots'] = repeated
        automatic, automatic_metric = probe.global_plan(automatic=True)
        require(automatic_metric['target']==target and xyz(automatic.path[-1])==target_xyz and
                probe.status()['repositioning_target']==target, 'Automatic global handoff selected a different target')
        summary['observations']['automatic_global_same_target'] = automatic_metric

        before_hypothetical = probe.status()
        _, metric = probe.plan(hypothetical=target_pose)
        after_hypothetical = probe.status()
        require(after_hypothetical['repositioning_active'] and after_hypothetical['repositioning_target']==target and
                after_hypothetical['low_gain_iterations']==before_hypothetical['low_gain_iterations'] and
                metric['auto_global']['reason']=='hypothetical_root',
                'Hypothetical near-target request changed actual mission state')
        summary['observations']['hypothetical_at_target'] = {'metrics': metric, 'global_status': after_hypothetical}
        ahead_request = PlanAhead.Request()
        ahead_request.header.frame_id, ahead_request.bound_mode, ahead_request.arrival_time = 'map', 3, 1.
        ahead_request.root_pose = copy.deepcopy(target_pose)
        count = probe.status()['low_gain_iterations']
        ahead = probe.call('planner_ahead', ahead_request, PlanAhead)
        require(ahead.global_required and not ahead.success and not ahead.path and not ahead.homing_required,
                'PlanAhead did not defer to the actual retained global trip')
        require(probe.status()['repositioning_target']==target and probe.status()['low_gain_iterations']==count,
                'Pending PlanAhead altered the retained target or no-frontier counter')
        summary['observations']['ahead_pending'] = {'reason': ahead.reason, 'global_required': ahead.global_required,
            'actual_distance_m': target_distance, 'hypothetical_distance_m': 0., 'counter_unchanged': True}

        # Move only synthetic odometry, not a robot. A 4.75 m remaining
        # distance avoids floating-point ambiguity exactly on the boundary.
        near = [value*(1.-4.75/target_distance) for value in target_xyz]
        probe.move(near)
        resumed, metric = probe.plan()
        state = probe.status()
        require(not state['repositioning_active'] and state['repositioning_target']==-1 and
                resumed.status==resumed.K_FORWARD and metric['gain_evaluated'],
                'Actual arrival within 5 m did not clear retention and restore local evaluation')
        summary['observations']['actual_arrival'] = {'position': near, 'distance_m': math.dist(near, target_xyz),
                                                    'metrics': metric, 'global_status': state}

        probe.move([0., 0., 0.])
        stop_checks = []
        for service, kind in (('pci_stop', PciStop), ('planner_control_interface/std_srvs/stop', Trigger)):
            probe.global_plan(automatic=True)
            require(probe.status()['repositioning_active'], 'Failed to reactivate native target for stop check')
            probe.until(lambda:probe.stop_pub.get_subscription_count()>=2, 'stop topic discovery')
            before = len(probe.stops)
            require(probe.call(service, kind.Request(), kind).success, service+' rejected')
            probe.until(lambda:len(probe.stops)>before and not probe.status()['repositioning_active'], service+' cleared target')
            require(probe.stops[before:]==[True], service+' did not emit exactly one explicit stop notification')
            stop_checks.append({'service': service, 'stop_messages': probe.stops[before:], 'global_status': probe.status()})
        summary['observations']['explicit_pci_stops'] = stop_checks

        probe.global_plan(automatic=True)
        require(probe.status()['repositioning_active'], 'Failed to reactivate native target for graph load')
        probe.storage()
        require(not probe.status()['repositioning_active'] and probe.status()['repositioning_target']==-1,
                'Graph replacement retained a target from the old graph')
        summary['observations']['graph_reload'] = probe.status()
        summary['checks'].update({'manual_global_stays_one_shot': True, 'fourth_local_round_retains_native_target': True,
            'actual_far_root_reuses_target_without_local_gain': True, 'automatic_global_preserves_target': True,
            'hypothetical_root_preserves_actual_state': True, 'ahead_defers_to_actual_pending_trip': True,
            'actual_within_5m_restores_local': True, 'both_explicit_pci_stops_clear_once': True,
            'graph_replacement_clears_target_ros2_adaptation': True})
        summary['status'] = 'passed'
    except Exception as error:
        summary['error'] = f'{type(error).__name__}: {error}'
        summary['traceback'] = traceback.format_exc()
        if probe is not None:
            summary['last_local_metrics'], summary['last_global_metrics'] = probe.metrics[-8:], probe.globals[-8:]
    finally:
        try:
            if probe is not None:
                probe.close()
            if initialized and rclpy.ok():
                rclpy.shutdown()
            summary['processes_stopped'] = True
        except Exception as error:
            summary['cleanup_error'], summary['status'] = str(error), 'failed'
        summary['elapsed_s'] = round(time.monotonic()-started, 3)
        temporary = output.with_suffix('.tmp')
        temporary.write_text(json.dumps(summary, ensure_ascii=False, indent=2, allow_nan=False)+'\n')
        temporary.replace(output)
        print(json.dumps({'status': summary['status'], 'output': str(output),
                          'error': summary.get('error'), 'elapsed_s': summary['elapsed_s']}, ensure_ascii=False))
    return 0 if summary['status']=='passed' else 1


if __name__ == '__main__':
    raise SystemExit(main())
